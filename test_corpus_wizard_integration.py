#!/usr/bin/env python
"""
Test script to verify corpus wizard integration fixes.

This script tests:
1. Retriever manifest reading (filters appearing in UI)
2. Target configuration generation
3. Environment variable updates
"""

import json
import sys
from pathlib import Path
import tempfile
import shutil

def test_retriever_manifest_reading():
    """Test that the retriever can correctly read manifest structure."""
    print("Testing retriever manifest reading...")

    # Create a test manifest
    test_manifest = {
        "corpus_name": "test_corpus",
        "fields": {
            "corpus": {
                "values": ["collection_1", "collection_2", "collection_3"]
            }
        },
        "statistics": {
            "total_documents": 100
        }
    }

    # Create temp directory for testing
    with tempfile.TemporaryDirectory() as tmpdir:
        manifest_path = Path(tmpdir) / "manifest.json"
        with open(manifest_path, 'w') as f:
            json.dump(test_manifest, f)

        # Test reading manifest
        with open(manifest_path, 'r') as f:
            loaded_manifest = json.load(f)

        # Check if we can access filter values correctly
        if "fields" in loaded_manifest and "corpus" in loaded_manifest["fields"]:
            corpus_field = loaded_manifest["fields"]["corpus"]
            if "values" in corpus_field:
                values = corpus_field["values"]
                print(f"  ✓ Found {len(values)} filter values: {values}")
                return True

        print("  ✗ Failed to read filter values from manifest")
        return False

