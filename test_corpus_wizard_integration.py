def main():
    """Run all integration tests."""
    print("=" * 60)
    print("Corpus Wizard Integration Tests")
    print("=" * 60)

    results = []

    # Run tests
    results.append(("Retriever Manifest Reading", test_retriever_manifest_reading()))
    results.append(("Target Config Generation", test_target_config_generation()))
    results.append(("Environment Variable Updates", test_env_variable_updates()))
    results.append(("Unified Configuration", test_unified_config()))

    # Summary
    print("\n" + "=" * 60)
    print("Test Summary")
    print("=" * 60)

    passed = sum(1 for _, result in results if result)
    total = len(results)

    for test_name, result in results:
        status = "✓ PASSED" if result else "✗ FAILED"
        print(f"{test_name:.<40} {status}")

    print(f"\nTotal: {passed}/{total} tests passed")

    if passed == total:
        print("\n✅ All integration tests passed!")
        return 0
    else:
        print(f"\n❌ {total - passed} test(s) failed")
        return 1

if __name__ == "__main__":
    sys.exit(main())