def test_env_variable_updates():
    """Test environment variable update logic."""
    print("\nTesting environment variable updates...")

    # Create a test .env file
    with tempfile.NamedTemporaryFile(mode='w', suffix='.env', delete=False) as f:
        f.write("# Test environment file\n")
        f.write("TEST_TARGET=old_target\n")
        f.write("VITE_SITE_TITLE=Old Title\n")
        f.write("OTHER_VAR=value\n")
        test_env_path = f.name

    try:
        # Read the file
        with open(test_env_path, 'r') as f:
            lines = f.readlines()

        # Update TEST_TARGET
        new_target = "k20_claude_3_5_haiku_20241022"
        for i, line in enumerate(lines):
            if line.strip().startswith('TEST_TARGET='):
                lines[i] = f'TEST_TARGET={new_target}\n'
                print(f"  ✓ Updated TEST_TARGET to {new_target}")
                break

        # Update VITE_SITE_TITLE
        new_title = "My Test Corpus"
        for i, line in enumerate(lines):
            if line.strip().startswith('VITE_SITE_TITLE='):
                lines[i] = f'VITE_SITE_TITLE={new_title}\n'
                print(f"  ✓ Updated VITE_SITE_TITLE to {new_title}")
                break

        # Write back
        with open(test_env_path, 'w') as f:
            f.writelines(lines)

        # Verify updates
        with open(test_env_path, 'r') as f:
            content = f.read()
            if f'TEST_TARGET={new_target}' in content and f'VITE_SITE_TITLE={new_title}' in content:
                print("  ✓ Environment variables updated successfully")
                return True
            else:
                print("  ✗ Environment variable update failed")
                return False

    finally:
        # Clean up
        Path(test_env_path).unlink(missing_ok=True)

